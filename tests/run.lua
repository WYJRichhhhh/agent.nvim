vim.o.columns = 220
vim.o.lines = 50
local root = vim.fn.getcwd()
vim.opt.rtp:prepend(root)
vim.cmd.runtime("plugin/agent.lua")
local agent = require("agent")
local python = vim.fn.exepath("python3")
assert(python ~= "", "测试需要 python3")
local command = { python, "-u", root .. "/tests/fixtures/fake_cli.py" }
local notifications = {}
vim.notify = function(message)
    notifications[#notifications + 1] = tostring(message)
end
local temp = vim.fn.tempname() .. " 中文 空格"
vim.fn.mkdir(temp .. "/other", "p")
temp = vim.uv.fs_realpath(temp)
local function text(buf)
    return table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), "\n")
end
local function wait_for(test, message)
    assert(vim.wait(3000, test, 20), message)
end
local function setup(layout)
    agent.setup({
        backend = "fake",
        cwd = temp,
        env = { AGENT_TEST_VALUE = "inherited-config" },
        window = { layout = layout or "float" },
        terminal = { start_insert = false, hide_key = "<M-a>" },
        backends = { fake = { command = command } },
    })
end
local checks = 0
local function check(name, fn)
    fn()
    checks = checks + 1
    print("PASS " .. name)
end
local ok, err = xpcall(function()
    check("配置初始化不启动进程，重复 setup 不重复注册事件", function()
        setup()
        local count = #vim.api.nvim_get_autocmds({ group = "AgentNvim" })
        setup()
        assert(#vim.api.nvim_get_autocmds({ group = "AgentNvim" }) == count)
        assert(agent.status().state == "idle")
    end)
    check("发现后端和命令补全", function()
        assert(vim.tbl_contains(require("agent.registry").available(), "fake"))
        assert(vim.fn.exists(":Agent") == 2)
        assert(vim.tbl_contains(vim.fn.getcompletion("Agent st", "cmdline"), "start"))
    end)
    check("首次启动：真实 PTY、目录含空格中文、环境覆盖", function()
        vim.cmd("Agent start fake")
        local state = agent.status()
        assert(state.state == "running" and state.visible)
        wait_for(function()
            return text(state.bufnr):find("READY", 1, true)
        end, "进程未就绪")
        assert(text(state.bufnr):find(temp, 1, true))
        assert(text(state.bufnr):find("env=inherited-config", 1, true))
        assert(vim.bo[state.bufnr].filetype == "agent_terminal")
    end)
    check("帮助可发现，查看帮助不终止会话，提示只显示一次", function()
        local state = agent.status()
        local pid = vim.fn.jobpid(state.job_id)
        vim.cmd.helptags(root .. "/doc")
        assert(vim.tbl_contains(vim.fn.getcompletion("Agent he", "cmdline"), "help"))
        local maps = vim.api.nvim_buf_get_keymap(state.bufnr, "n")
        assert(vim.iter(maps):any(function(map)
            return map.lhs == "?"
        end))
        vim.cmd("Agent help")
        assert(vim.bo.filetype == "help")
        assert(vim.fn.expand("%:t") == "agent.nvim.txt")
        vim.cmd.close()
        agent.hide()
        agent.open()
        assert(agent.status().job_id == state.job_id)
        assert(vim.fn.jobpid(state.job_id) == pid)
        local hints = vim.iter(notifications)
            :filter(function(message)
                return message:find("q 隐藏，? 帮助", 1, true) ~= nil
            end)
            :totable()
        assert(#hints == 1)
    end)
    check("快速 toggle 保留进程和终端 buffer，隐藏时仍可执行", function()
        local state = agent.status()
        local pid = vim.fn.jobpid(state.job_id)
        for _ = 1, 12 do
            agent.toggle()
        end
        assert(agent.status().bufnr == state.bufnr and agent.status().job_id == state.job_id)
        assert(vim.fn.jobpid(state.job_id) == pid)
        vim.api.nvim_chan_send(state.job_id, "中文输入\n")
        wait_for(function()
            return text(state.bufnr):find("REPLY:中文输入", 1, true)
        end, "交互未返回")
        agent.hide()
        vim.api.nvim_chan_send(state.job_id, "hidden-task\n")
        wait_for(function()
            return text(state.bufnr):find("REPLY:hidden-task", 1, true)
        end, "隐藏中断进程")
        agent.open()
        assert(text(state.bufnr):find("REPLY:中文输入", 1, true))
    end)
    check("未提交的输入在 hide/show 后保留", function()
        local state = agent.status()
        vim.api.nvim_chan_send(state.job_id, "unfinished")
        agent.hide()
        agent.open()
        vim.api.nvim_chan_send(state.job_id, "-continued\n")
        wait_for(function()
            return text(state.bufnr):find("REPLY:unfinished-continued", 1, true)
        end, "输入丢失")
    end)
    check("编辑器换目录不另开进程，运行中拒绝切换后端", function()
        local state = agent.status()
        vim.cmd.cd({ args = { temp .. "/other" } })
        agent.hide()
        agent.open()
        assert(agent.status().job_id == state.job_id and agent.status().cwd == temp)
        agent.open("codex")
        agent.start("codex")
        assert(agent.status().job_id == state.job_id)
    end)
    check("聚焦与返回编辑窗口，手动关窗后复用进程", function()
        agent.hide()
        local editor = vim.api.nvim_get_current_win()
        local buf = vim.api.nvim_get_current_buf()
        agent.focus()
        local state = agent.status()
        agent.focus()
        assert(vim.api.nvim_get_current_win() == editor and vim.api.nvim_get_current_buf() == buf)
        agent.open()
        vim.api.nvim_win_close(vim.api.nvim_get_current_win(), true)
        agent.open()
        assert(agent.status().job_id == state.job_id)
        vim.api.nvim_exec_autocmds("VimResized", {})
    end)
    check("异常退出保留输出，普通唤起不自动另开，会话可显式重启", function()
        local state = agent.status()
        vim.api.nvim_chan_send(state.job_id, "EXIT\n")
        wait_for(function()
            return agent.status().state == "exited"
        end, "退出回调未运行")
        assert(agent.status().exit_code == 7)
        agent.hide()
        agent.open()
        assert(agent.status().job_id == state.job_id)
        agent.start("fake")
        assert(agent.status().job_id ~= state.job_id and agent.status().state == "running")
    end)
    check("显式停止、旧回调隔离和新会话", function()
        local old = agent.status()
        assert(agent.stop())
        assert(vim.fn.jobwait({ old.job_id }, 0)[1] ~= -1)
        agent.start("fake")
        local current = agent.status()
        vim.wait(100)
        assert(agent.status().job_id == current.job_id and current.state == "running")
    end)
    check("删除终端 buffer 停止进程并清理状态", function()
        local state = agent.status()
        vim.api.nvim_buf_delete(state.bufnr, { force = true })
        assert(agent.status().state == "idle")
        wait_for(function()
            return vim.fn.jobwait({ state.job_id }, 0)[1] ~= -1
        end, "残留进程")
    end)
    check("底部和右侧分屏显示及隐藏", function()
        for _, layout in ipairs({ "bottom", "right" }) do
            setup(layout)
            agent.start("fake")
            assert(vim.api.nvim_win_get_config(vim.api.nvim_get_current_win()).relative == "")
            local state = agent.status()
            agent.toggle()
            agent.toggle()
            assert(agent.status().job_id == state.job_id)
            assert(agent.stop())
        end
    end)
    check("默认空环境覆盖可启动，并继承父进程环境", function()
        vim.env.AGENT_TEST_VALUE = "parent-value"
        agent.setup({
            backend = "fake",
            cwd = temp,
            terminal = { start_insert = false },
            backends = { fake = { command = command } },
        })
        agent.start("fake")
        local state = agent.status()
        assert(state.state == "running")
        wait_for(function()
            return text(state.bufnr):find("env=parent-value", 1, true)
        end, "父进程环境未继承")
        assert(agent.stop())
        vim.env.AGENT_TEST_VALUE = nil
    end)
    check("无效命令和配置不会创建残留会话", function()
        agent.register_backend("missing", { command = { "not-an-installed-agent-cli" } })
        agent.start("missing")
        assert(agent.status().state == "idle")
        assert(not pcall(agent.setup, { window = { layout = "invalid" } }))
    end)
    check("显式恢复使用后端命令和原目录，不替换运行中的进程", function()
        setup()
        agent.register_backend("fake", {
            command = command,
            resume_command = { python, "-u", root .. "/tests/fixtures/fake_cli.py", "--resume-test" },
        })
        agent.start("fake")
        local original = agent.status()
        agent.resume("fake")
        assert(agent.status().job_id == original.job_id)
        vim.api.nvim_chan_send(original.job_id, "EXIT\n")
        wait_for(function()
            return agent.status().state == "exited"
        end, "退出回调未运行")
        vim.cmd.cd({ args = { temp .. "/other" } })
        vim.cmd("Agent resume fake")
        local resumed = agent.status()
        assert(resumed.job_id ~= original.job_id and resumed.cwd == temp)
        wait_for(function()
            return text(resumed.bufnr):find("ARGS:--resume-test", 1, true)
        end, "没有使用恢复命令")
        assert(agent.stop())
        assert(not pcall(agent.register_backend, "bad-resume", { command = command, resume_command = {} }))
    end)
    check("启动不依赖系统 shell，后端环境覆盖优先", function()
        setup()
        local old_shell, old_env_shell = vim.o.shell, vim.env.SHELL
        vim.o.shell = "/not-an-installed-shell"
        vim.env.SHELL = "/not-an-installed-shell"
        agent.register_backend("fake", { command = command, env = { AGENT_TEST_VALUE = "backend-wins" } })
        agent.start("fake")
        local current = agent.status()
        wait_for(function()
            return text(current.bufnr):find("env=backend-wins", 1, true)
        end, "直接启动失败或环境覆盖错误")
        assert(agent.stop())
        vim.o.shell, vim.env.SHELL = old_shell, old_env_shell
    end)
    check("主题更新只修改窗口高亮，不重启进程", function()
        setup()
        local old = vim.api.nvim_get_hl(0, { name = "NormalFloat", link = false })
        agent.start("fake")
        local current = agent.status()
        local pid = vim.fn.jobpid(current.job_id)
        vim.api.nvim_set_hl(0, "NormalFloat", { fg = "#cdd6f4", bg = "#1e1e2e" })
        vim.api.nvim_exec_autocmds("ColorScheme", { pattern = "agent-test" })
        wait_for(function()
            return vim.api.nvim_get_hl(0, { name = "AgentNormal", link = false }).bg == 0x1e1e2e
        end, "未更新窗口主题")
        assert(agent.status().job_id == current.job_id and vim.fn.jobpid(current.job_id) == pid)
        assert(agent.stop())
        vim.api.nvim_set_hl(0, "NormalFloat", old)
    end)
    check("运行中切换后端：当前项只聚焦、取消保留输入、确认才替换", function()
        setup()
        agent.register_backend("fake2", { command = command })
        agent.start("fake")
        local original = agent.status()
        local real_select = vim.ui.select
        local pending
        vim.ui.select = function(_, _, cb)
            pending = cb
        end
        agent.select()
        pending("fake")
        assert(agent.status().job_id == original.job_id and agent.status().visible)
        vim.api.nvim_chan_send(original.job_id, "unfinished")
        agent.select()
        pending("fake2")
        assert(agent.status().job_id == original.job_id)
        pending("取消")
        assert(agent.status().job_id == original.job_id)
        vim.api.nvim_chan_send(original.job_id, "-kept\n")
        wait_for(function()
            return text(original.bufnr):find("REPLY:unfinished-kept", 1, true)
        end, "取消切换丢失输入")
        agent.select()
        pending("fake2")
        pending("停止当前会话并切换")
        assert(agent.status().backend == "fake2" and agent.status().job_id ~= original.job_id)
        assert(vim.fn.jobwait({ original.job_id }, 0)[1] ~= -1, "旧进程仍在运行")
        vim.ui.select = real_select
        assert(agent.stop())
    end)
    check("停止操作使尚未完成的切换确认失效", function()
        setup()
        agent.register_backend("fake2", { command = command })
        agent.start("fake")
        local real_select = vim.ui.select
        local pending
        vim.ui.select = function(_, _, cb)
            pending = cb
        end
        agent.select()
        pending("fake2")
        local confirm = pending
        assert(agent.stop())
        confirm("停止当前会话并切换")
        assert(agent.status().state == "idle")
        vim.ui.select = real_select
    end)
    check("异步选择只启动一次，取消选择不会产生会话", function()
        setup()
        local real_select = vim.ui.select
        local callback, called = nil, 0
        vim.ui.select = function(_, _, cb)
            called = called + 1
            callback = cb
        end
        agent.register_backend("fake2", { command = command })
        agent.select()
        agent.select()
        assert(called == 1)
        callback(nil)
        assert(agent.status().state == "idle")
        agent.select()
        agent.stop()
        callback("fake")
        assert(agent.status().state == "idle")
        agent.select()
        callback("fake")
        assert(agent.status().state == "running")
        vim.ui.select = real_select
        assert(agent.stop())
    end)
end, debug.traceback)
agent.stop()
vim.cmd.cd({ args = { root } })
vim.fn.delete(temp, "rf")
if not ok then
    print(err)
    vim.cmd("cquit 1")
else
    print("AGENT_TEST_OK " .. checks .. " checks")
    vim.cmd("qa!")
end
